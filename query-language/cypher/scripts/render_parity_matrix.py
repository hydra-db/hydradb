#!/usr/bin/env python3
"""Render query-language/cypher/parity/legacy-read-parity.json to a Markdown table.

The JSON is the matrix; this file is how a reviewer reads it. The Markdown is
generated and never hand-edited, and `--check` fails when it has drifted from
the JSON, so a row cannot be added without the readable copy following it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

MATRIX = Path(__file__).resolve().parent.parent / "parity" / "legacy-read-parity.json"
RENDERED = MATRIX.with_suffix(".md")

HEADER = (
    "id",
    "traits",
    "legacy path",
    "legacy",
    "engine",
    "multiplicity / ordering",
    "error class",
    "neo4j",
    "AB",
    "owner",
    "test",
)


INLINE_WIDTH = 100


def dumps(value: object, indent: int = 0) -> str:
    """Serialize the matrix with small structures kept on one line.

    `json.dumps(indent=2)` spreads `{"string": "alpha"}` over five lines, which
    turns a row into a screenful and the file into something nobody edits by
    hand. Anything that fits in `INLINE_WIDTH` stays inline; only what does not
    is indented. The result is stable, so `--check` can compare bytes.
    """
    flat = json.dumps(value, ensure_ascii=False)
    if len(flat) + indent <= INLINE_WIDTH or not isinstance(value, (dict, list)):
        return flat
    pad = " " * (indent + 2)
    if isinstance(value, dict):
        items = [f"{pad}{json.dumps(key)}: {dumps(item, indent + 2)}" for key, item in value.items()]
        return "{\n" + ",\n".join(items) + "\n" + " " * indent + "}"
    items = [f"{pad}{dumps(item, indent + 2)}" for item in value]
    return "[\n" + ",\n".join(items) + "\n" + " " * indent + "]"


def cell(value: str) -> str:
    return value.replace("|", "\\|")


def neo4j_column(row: dict) -> str:
    """What the Neo4j oracle holds this row to (query-language/cypher/scripts/neo4j_parity_oracle.py)."""
    expectation = row.get("neo4j")
    if expectation:
        return {"error": "refuses", "rows": "target rows"}[expectation["expect"]]
    if "excluded" in (row["legacy"], row["engine"]):
        return "-"
    if "supported" in (row["legacy"], row["engine"]):
        return "rows"
    return "unrecorded"


def render(matrix: dict) -> str:
    lines = [
        "<!-- Generated by query-language/cypher/scripts/render_parity_matrix.py. Do not edit. -->",
        "",
        "# Legacy read parity matrix",
        "",
        "One row per query shape. The source of truth is",
        "`query-language/cypher/parity/legacy-read-parity.json`; this file is rendered from it and",
        "`just test-parity-matrix` fails when the two disagree.",
        "",
        "The `neo4j` column is what `just neo4j-oracle` holds the row to: `rows`",
        "means Neo4j must return the recorded rows, `refuses` that Neo4j must refuse",
        "the query too, `target rows` the recorded answer for a shape the engine does",
        "not run yet, and `unrecorded` a gap whose answer nobody has written down.",
        "",
        f"Rows: {len(matrix['rows'])}. "
        f"Marked as candidates for the live Bolt and HTTP gate: {sum(1 for row in matrix['rows'] if row['ab'])}.",
        "",
        "## Bookmarks",
        "",
        cell(matrix["bookmarks"]["statement"]),
        "",
        f"Reviewed by {cell(matrix['bookmarks']['reviewer'])}.",
        "",
        "## Shapes",
        "",
        "| " + " | ".join(HEADER) + " |",
        "| " + " | ".join("--" for _ in HEADER) + " |",
    ]
    for row in matrix["rows"]:
        lines.append(
            "| "
            + " | ".join(
                cell(value)
                for value in (
                    row["id"],
                    ", ".join(row["traits"]),
                    f"`{row['legacy_path']}`",
                    row["legacy"],
                    row["engine"],
                    f"{row['multiplicity']} / {row['ordering']}",
                    row["error_class"] or "-",
                    neo4j_column(row),
                    "yes" if row["ab"] else "-",
                    row["owner"],
                    f"`{row['test_ref']}`",
                )
            )
            + " |"
        )

    excluded = [row for row in matrix["rows"] if "exclusion" in row]
    if excluded:
        lines += ["", "## Reviewed exclusions", ""]
        for row in excluded:
            lines += [
                f"### {cell(row['id'])}",
                "",
                cell(row["exclusion"]["reason"]),
                "",
                f"Reviewed by {cell(row['exclusion']['reviewer'])}.",
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the rendered file is stale instead of rewriting it",
    )
    arguments = parser.parse_args()
    matrix = json.loads(MATRIX.read_text())
    rendered = render(matrix)
    formatted = dumps(matrix) + "\n"
    if arguments.check:
        stale = [
            path
            for path, want in ((RENDERED, rendered), (MATRIX, formatted))
            if (path.read_text() if path.exists() else "") != want
        ]
        if stale:
            names = ", ".join(str(path) for path in stale)
            print(f"{names} is stale; run `just parity-matrix`", file=sys.stderr)
            raise SystemExit(1)
        return
    MATRIX.write_text(formatted)
    RENDERED.write_text(rendered)
    print(f"wrote {RENDERED} and normalized {MATRIX.name}")


if __name__ == "__main__":
    main()
