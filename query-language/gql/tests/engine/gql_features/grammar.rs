//! The mandatory GQL grammar: every production of ISO/IEC 39075:2024, as
//! Technical Corrigendum 1:2026 amends it, that minimum conformance (§24.2)
//! allows, each with the `FEATURES` row whose probe exercises it.
//!
//! The list was derived from the books, not from this engine:
//!
//! 1. Take every BNF production in the Format sections of Clauses 6 to 21.
//! 2. Apply every Conformance Rule of Clauses 6 to 23, as Corrigendum 1
//!    adds, replaces and deletes them. A rule that forbids a production
//!    outright removes it; a rule that forbids one form of it removes that
//!    alternative. Rules with no feature ID remove specification devices
//!    (`TEMP`, `NO BINDINGS`, `GROUP` list types).
//! 3. Remove what Syntax Rules tie to a removed production: a data-modifying
//!    statement must contain `INSERT`, `SET`, `REMOVE` or `DELETE` (§13.1
//!    Syntax Rule 5), and a catalog-modifying or data-modifying procedure
//!    must contain such statements (§9.1 Syntax Rules 5 and 6).
//! 4. Keep what is reachable from `<GQL-program>`, plus the lexical
//!    productions of §21.3 (identifiers, comments). Single characters
//!    (§21.4) are left out.
//!
//! The books are not in this repository, so the derivation is not rerun
//! here. The test holds every production to exactly one mandatory row, so a
//! row cannot be dropped without the grammar it covers moving elsewhere.
//! When a corrigendum or a new edition changes the grammar or its
//! Conformance Rules, rerun the derivation and update this list.

