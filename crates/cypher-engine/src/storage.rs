use async_trait::async_trait;
use hydradb_cypher_ast::GqlStatus;

use crate::{
    BoundedVertexIds, ExpandDirection, ExpandNeighbor, ExpandRequest, GraphPhysicalPlan, OrderedPropertyEntryPage, OrderedPropertyScanPage,
    OrderedPropertyScanRequest, OrderedRelationshipPropertyScanPage, OrderedRelationshipPropertyScanRequest, PropertyEqualityCandidate,
    PropertyPointSet, ReadRequest, RelationshipRecord, ScalarValue, StatisticsAccessReport, StorageResult, VertexId, VertexRecord,
    VertexStorageScanPage, VertexStorageScanRequest,
};

/// One consistent graph read view used for an entire physical plan.
// async_trait adds #[must_use] to boxed futures; Rust 1.99 already marks Future must_use.
#[allow(clippy::double_must_use, reason = "redundant attribute is generated by async_trait")]
#[async_trait]
pub trait GraphRead: Send {
    /// Cooperative execution checkpoint for CPU-side operator work. Storage
    /// adapters can use this to surface cancellation or deadline expiry while
    /// the engine is processing already-fetched records.
    fn checkpoint(&self, _operation: &'static str) -> StorageResult<()> {
        Ok(())
    }

    /// Admit an intermediate row collection before it grows further. The
    /// default keeps standalone backends unconstrained; production adapters
    /// should enforce their configured query work limits here.
    fn check_intermediate_rows(&self, operation: &'static str, _rows: usize) -> StorageResult<()> {
        self.checkpoint(operation)
    }

    /// The largest intermediate row collection
    /// [`Self::check_intermediate_rows`] admits, when the backend enforces
    /// one. Per-request memory the engine keeps outside any single operator,
    /// such as the hydration identity map, is bounded by the same number.
    /// `None`, the default, means unbounded.
    fn max_intermediate_rows(&self) -> Option<usize> {
        None
    }

    /// Execute one typed vertex storage scan.
    ///
    /// The default preserves the established backend contracts while callers
    /// migrate to one physical scan leaf. Backends may override this method to
    /// combine point spans or route all families through one storage primitive.
    async fn scan_vertex_storage(&mut self, request: &VertexStorageScanRequest) -> StorageResult<VertexStorageScanPage> {
        let page = match request {
            VertexStorageScanRequest::IdPoints { ids } => VertexStorageScanPage::Ids(ids.clone()),
            VertexStorageScanRequest::PropertyPoints { property, points } => {
                let ids = match points {
                    PropertyPointSet::Single(value) => self.seek_vertices_by_property(property, value).await?,
                    PropertyPointSet::Multiple(values) => self.seek_vertices_by_property_values(property, values).await?,
                };
                VertexStorageScanPage::Ids(ids)
            }
            VertexStorageScanRequest::PropertyPresence { property } => {
                VertexStorageScanPage::Ids(self.scan_vertices_by_property(property).await?)
            }
            VertexStorageScanRequest::OrderedProperty(request) => {
                VertexStorageScanPage::Ordered(self.scan_vertices_by_property_ordered(request).await?)
            }
            VertexStorageScanRequest::LabelPrefix { label, max_results } => {
                VertexStorageScanPage::Ids(self.scan_vertices_by_label(label, *max_results).await?)
            }
            VertexStorageScanRequest::AllVertices => VertexStorageScanPage::Ids(self.scan_all_vertices().await?),
        };
        Ok(page)
    }

    /// Return vertices whose stored property is Cypher-equal to `value`.
    /// Implementations must include equivalent numeric representations such as
    /// integer `1` and float `1.0`; exact KV encoding is a backend concern.
    async fn seek_vertices_by_property(&mut self, property: &str, value: &ScalarValue) -> StorageResult<Vec<VertexId>>;

    /// Return vertices whose stored property is Cypher-equal to any of
    /// `values`, as the union of one seek per value. Backends that can issue
    /// the seeks together should override this: the default runs them one
    /// after another, which on a remote object store is one round trip per
    /// value. Duplicates across values may be returned; the engine dedupes.
    async fn seek_vertices_by_property_values(&mut self, property: &str, values: &[ScalarValue]) -> StorageResult<Vec<VertexId>> {
        let mut ids = Vec::new();
        for value in values {
            self.checkpoint("cypher_multi_seek")?;
            ids.extend(self.seek_vertices_by_property(property, value).await?);
        }
        Ok(ids)
    }

    /// Return vertices carrying `property`, regardless of its value. This is
    /// the anchored fallback for non-equality predicates such as ranges,
    /// inequality, and string prefixes.
    async fn scan_vertices_by_property(&mut self, property: &str) -> StorageResult<Vec<VertexId>>;

    /// Walk one vertex property index in order and return hydrated vertices
    /// for a bounded window. See [`OrderedPropertyScanRequest`] for the
    /// contract; this is what lets `ORDER BY p LIMIT n` and keyset pages read
    /// only the prefix of the index they need instead of the whole property.
    /// The engine owns the window: it applies any residual predicate, keeps
    /// the best rows, and pulls further pages (passing `last` back as `after`)
    /// until the window and its boundary tie are decided.
    async fn scan_vertices_by_property_ordered(&mut self, request: &OrderedPropertyScanRequest) -> StorageResult<OrderedPropertyScanPage>;

    /// [`Self::scan_vertices_by_property_ordered`] without the records: the
    /// same entries, each as the vertex id and the walked property's value.
    /// The engine asks for this when nothing in the plan reads the vertex
    /// beyond those, so a backend whose record read is the walk's main cost
    /// can leave it out; every other guarantee of the record walk holds,
    /// including that each entry names an existing vertex with the labels.
    ///
    /// The default walks the records and keeps only what this page carries,
    /// which is correct for any backend and saves nothing.
    async fn scan_vertex_entries_by_property_ordered(
        &mut self,
        request: &OrderedPropertyScanRequest,
    ) -> StorageResult<OrderedPropertyEntryPage> {
        let page = self.scan_vertices_by_property_ordered(request).await?;
        let entries = page
            .vertices
            .into_iter()
            .map(|vertex| match vertex.properties.get(request.property.as_str()) {
                Some(value) => Ok((vertex.id, value.clone())),
                // The record walk's contract says every row carries the
                // walked property; a row without it is a backend fault, not
                // an entry to drop.
                None => Err(crate::StorageError::new(format!(
                    "ordered scan of {} returned vertex {} without the property",
                    request.property, vertex.id
                ))),
            })
            .collect::<StorageResult<Vec<_>>>()?;
        Ok(OrderedPropertyEntryPage {
            entries,
            last: page.last,
            exhausted: page.exhausted,
            index_entries: page.index_entries,
        })
    }

    /// [`Self::scan_vertex_entries_by_property_ordered`] for a caller that
    /// keeps nothing past the page it is reading, such as a count. Its reads
    /// are charged to the backend's scan allowance rather than its index
    /// candidate cap: that cap bounds what a query may hold, and this caller
    /// holds one page, so a walk over more entries than the cap still runs,
    /// bounded by what it reads. `max_index_entries` bounds each page.
    ///
    /// `None` where the backend has no such walk; the engine then runs the
    /// access the plan chose, under its usual caps. The default.
    async fn scan_vertex_entries_by_property_for_count(
        &mut self,
        _request: &OrderedPropertyScanRequest,
    ) -> StorageResult<Option<OrderedPropertyEntryPage>> {
        Ok(None)
    }

    /// Walk one relationship property index in order and return one page of
    /// relationships. See [`OrderedRelationshipPropertyScanRequest`]. The
    /// default fails: a backend without an ordered relationship property index
    /// must say so rather than let the engine widen the walk to a scan.
    async fn scan_relationships_by_property_ordered(
        &mut self,
        request: &OrderedRelationshipPropertyScanRequest,
    ) -> StorageResult<OrderedRelationshipPropertyScanPage> {
        Err(crate::StorageError::new(format!(
            "this backend has no ordered index over relationship property {}.{}",
            request.relationship_type, request.property
        )))
    }

    /// Return matching vertices in ascending ID order. `max_results` is a
    /// semantic bound from a safe LIMIT pushdown, not a best-effort hint.
    async fn scan_vertices_by_label(&mut self, label: &str, max_results: Option<usize>) -> StorageResult<Vec<VertexId>>;

    /// [`Self::seek_vertices_by_property_values`] under a guard: the
    /// vertices, or `None` once the seek proves to hold more than
    /// `max_index_entries` index entries. `None` is always correct -- the
    /// caller then runs the plan it would have run without statistics -- so a
    /// backend may decline sooner, for example at a ceiling of its own.
    ///
    /// The default declines at once. Seeking everything and judging after
    /// would read the whole match before a stale estimate could decline,
    /// which is the work the guard exists to bound; a backend without a
    /// cheap bounded walk instead runs the plan chosen without statistics.
    async fn seek_vertices_by_property_values_bounded(
        &mut self,
        _property: &str,
        _values: &[ScalarValue],
        _max_index_entries: usize,
    ) -> StorageResult<BoundedVertexIds> {
        Ok(BoundedVertexIds::declined(0))
    }

    /// [`Self::scan_vertices_by_label`] under a guard: the label's vertices
    /// in ascending ID order, or `None` once it proves to hold more than
    /// `max_index_entries`. As for the bounded seek, `None` is always
    /// correct.
    async fn scan_vertices_by_label_bounded(&mut self, label: &str, max_index_entries: usize) -> StorageResult<BoundedVertexIds> {
        let ids = self
            .scan_vertices_by_label(label, Some(max_index_entries.saturating_add(1)))
            .await?;
        Ok(BoundedVertexIds::within(ids, max_index_entries))
    }

    async fn scan_all_vertices(&mut self) -> StorageResult<Vec<VertexId>>;

    /// Return relationships whose stored property is Cypher-equal to `value`.
    /// Implementations must consult both structural-edge and identified-
    /// relationship property indexes when the backing graph distinguishes them.
    async fn seek_relationships_by_property(
        &mut self,
        relationship_type: &str,
        property: &str,
        value: &ScalarValue,
    ) -> StorageResult<Vec<RelationshipRecord>>;

    /// Return relationships whose stored property is Cypher-equal to any of
    /// `values`, as the union of one [`Self::seek_relationships_by_property`]
    /// per value. The relationship counterpart of
    /// [`Self::seek_vertices_by_property_values`]: the default runs the seeks
    /// one after another, and a backend that can overlap them should
    /// override it. A relationship may be returned more than once; the engine
    /// dedupes by relationship identity.
    async fn seek_relationships_by_property_values(
        &mut self,
        relationship_type: &str,
        property: &str,
        values: &[ScalarValue],
    ) -> StorageResult<Vec<RelationshipRecord>> {
        let mut relationships = Vec::new();
        for value in values {
            self.checkpoint("cypher_relationship_multi_seek")?;
            relationships.extend(self.seek_relationships_by_property(relationship_type, property, value).await?);
        }
        Ok(relationships)
    }

    /// Probe a numeric lower-bound relationship index with bounded work.
    /// `None` means the index was too broad or unavailable; the physical plan
    /// then runs its ordinary expansion fallback.
    ///
    /// The result is a candidate superset, not an answer: the plan always
    /// re-applies the full predicate, labels and window. `lower`/`inclusive`
    /// may prune relationships that definitely fail the bound, never more.
    async fn probe_relationships_by_property_lower_bound(
        &mut self,
        _relationship_type: &str,
        _property: &str,
        _lower: &ScalarValue,
        _inclusive: bool,
        _max_index_entries: usize,
    ) -> StorageResult<Option<Vec<RelationshipRecord>>> {
        Ok(None)
    }

    /// Read a whole relationship type with bounded work, for a pattern rare
    /// enough that its edge population is cheaper than the anchor label's
    /// vertex population. `None` means the type proved too broad, or the
    /// backend cannot answer; the physical plan then runs its ordinary
    /// label-anchored fallback.
    ///
    /// This is the measurement the planner could not make: a backend that
    /// finishes inside `max_index_entries` has proven both that the type is
    /// rare and what it contains, so no statistic is consulted and a type that
    /// grows dense stops being probed without anyone retuning a threshold.
    ///
    /// Unlike the property probes, the result is an answer and not a candidate
    /// superset: every relationship of that type visible to the read is
    /// present. The caller still applies endpoint labels and the enclosing
    /// predicate and window. Returning a subset would silently drop rows, so a
    /// backend that cannot enumerate the type completely within its budget must
    /// return `None`.
    ///
    /// Records come back in their natural source-to-target orientation and the
    /// caller applies the pattern's direction, exactly as
    /// [`Self::seek_relationships_by_property`] does. Filtering by direction
    /// here would be wrong for an undirected hop, which matches one edge under
    /// both assignments.
    async fn probe_relationships_by_type(
        &mut self,
        _relationship_type: &str,
        _max_index_entries: usize,
    ) -> StorageResult<Option<Vec<RelationshipRecord>>> {
        Ok(None)
    }

    /// Return relationships incident to the requested input vertices. Results
    /// may be unordered and duplicated; the engine validates direction/type,
    /// deduplicates by relationship identity, and imposes result order.
    async fn expand_relationships(&mut self, request: &ExpandRequest) -> StorageResult<Vec<RelationshipRecord>>;

    /// The first half of [`Self::expand_relationships`]: the neighbours each
    /// input reaches, without reading a relationship record. The engine uses
    /// it under a `LIMIT`, reading records with
    /// [`Self::expand_relationships_between`] only for the neighbours the
    /// window still needs.
    ///
    /// Results may be unordered and duplicated. A listed neighbour whose
    /// relationships turn out not to exist yields no rows. `None`, the
    /// default, means listing is no cheaper than expanding, and the engine
    /// calls [`Self::expand_relationships`] instead.
    async fn expand_neighbors(&mut self, _request: &ExpandRequest) -> StorageResult<Option<Vec<ExpandNeighbor>>> {
        Ok(None)
    }

    /// Ordered, distinct outgoing targets for one input and type, strictly after
    /// the cursor. A short page exhausts the listing. A backend may decline the
    /// first page, but subsequent pages must use the same immutable listing.
    async fn outgoing_neighbor_page(
        &mut self,
        _input: VertexId,
        _edge_type: &str,
        _after: Option<VertexId>,
        _size: usize,
    ) -> StorageResult<Option<Vec<VertexId>>> {
        Ok(None)
    }

    /// The second half of [`Self::expand_relationships`]: the relationships
    /// from each listed input to its neighbour over that neighbour's type, in
    /// `direction`. Together with [`Self::expand_neighbors`] it must return
    /// the records `expand_relationships` would for the same pairs, with the
    /// same identities. Results may be unordered and duplicated.
    ///
    /// The default expands the listed inputs whole and keeps the listed
    /// pairs: correct for any backend, and no cheaper, which is why only a
    /// backend that overrides `expand_neighbors` is asked.
    async fn expand_relationships_between(
        &mut self,
        direction: ExpandDirection,
        neighbors: &[ExpandNeighbor],
    ) -> StorageResult<Vec<RelationshipRecord>> {
        let wanted = neighbors
            .iter()
            .map(|neighbor| (neighbor.input, neighbor.neighbor, neighbor.relationship_type.as_str()))
            .collect::<std::collections::BTreeSet<_>>();
        if wanted.is_empty() {
            return Ok(Vec::new());
        }
        let request = ExpandRequest {
            input_vertex_ids: wanted
                .iter()
                .map(|(input, ..)| *input)
                .collect::<std::collections::BTreeSet<_>>()
                .into_iter()
                .collect(),
            direction,
            relationship_types: wanted
                .iter()
                .map(|(.., relationship_type)| relationship_type.to_string())
                .collect::<std::collections::BTreeSet<_>>()
                .into_iter()
                .collect(),
        };
        let relationships = self.expand_relationships(&request).await?;
        Ok(relationships
            .into_iter()
            .filter(|relationship| {
                let (input, neighbor) = match direction {
                    ExpandDirection::Outgoing => (relationship.source, relationship.target),
                    ExpandDirection::Incoming => (relationship.target, relationship.source),
                };
                wanted.contains(&(input, neighbor, relationship.relationship_type.as_str()))
            })
            .collect())
    }

    /// Return the records of the existing vertices among `vertex_ids`, in any
    /// order. The engine calls this through a per-request identity map (see
    /// `hydration.rs`), so within one read session a backend is asked for a
    /// vertex at most once while the map has room.
    async fn hydrate_vertices(&mut self, vertex_ids: &[VertexId]) -> StorageResult<Vec<VertexRecord>>;

    /// Rank equality candidates by a bounded index probe and return the
    /// vertices of the most selective one, or `None` to keep the planned
    /// access path.
    ///
    /// The planner picks an access path before it knows how many vertices any
    /// index actually holds. When several equalities restrict the same
    /// binding, this lets the backend measure instead: give each candidate a
    /// slice of one fixed budget, walk its index, and discard any candidate
    /// that exhausts its slice as too broad to be worth seeking on. A
    /// candidate that finishes inside its slice has proven both that it is
    /// selective and what it matches, so its vertices are returned directly.
    ///
    /// Returning `Some` asserts the vertices are a complete superset of the
    /// rows satisfying that one candidate; the caller still applies labels and
    /// the full predicate. `None` is always safe and is the default, because a
    /// backend without index statistics or a cheap bounded walk has nothing to
    /// add to the planner's choice.
    ///
    /// The engine offers every equality it found rather than a shortlist,
    /// because only the backend knows what a walk costs. A backend is expected
    /// to rank a bounded prefix and ignore the rest: the walks are concurrent,
    /// and one candidate per property of a wide pattern is fan-out no caller
    /// asked for.
    async fn probe_selective_equality(&mut self, _candidates: &[PropertyEqualityCandidate]) -> StorageResult<Option<Vec<VertexId>>> {
        Ok(None)
    }

    // ---- Operator observation (Workstream 11) ----------------------------
    //
    // The executor calls the two dispatch hooks around every physical
    // operator invocation, and nothing else in it knows profiling exists. A
    // backend that wants per-operator numbers keeps a
    // [`crate::OperatorProfiler`] and forwards these to it; the defaults cost
    // one virtual call each.

    /// A physical operator is about to run. Invocations nest: a parent's
    /// hook fires before its inputs' and finishes after them.
    fn operator_started(&mut self, _plan: &GraphPhysicalPlan) {}

    /// The operator started by the matching [`Self::operator_started`]
    /// produced `rows_out` rows (zero when it failed).
    fn operator_finished(&mut self, _plan: &GraphPhysicalPlan, _rows_out: usize) {}

    /// An unbound all-vertex scan is about to ask storage for vertices.
    /// Correlated AllVertexScan operators that return a seed do not call this.
    fn record_full_scan(&self) {}

    /// Record a completion condition the query raised (GQL §4.9.3), such as
    /// the warning `01G11` an aggregate raises when it skips a null. The
    /// engine raises each one once per projection that met it.
    ///
    /// A backend that keeps them hands them back from
    /// [`Self::take_completion_conditions`], which is how they reach the
    /// execution outcome. Implementations must explicitly collect or forward
    /// conditions; silently discarding them would change GQLSTATUS.
    fn raise_completion_condition(&mut self, status: GqlStatus);

    /// Every completion condition raised on this read since the last call,
    /// in the order they were raised.
    fn take_completion_conditions(&mut self) -> Vec<GqlStatus>;

    /// A sibling read for running an independent plan branch, such as one arm
    /// of a `UNION`, at the same time as others. It must read the same
    /// snapshot and draw on the same per-query limits as this read, so running
    /// branches side by side changes neither what they see nor what they may
    /// spend; only its completion conditions are its own. `None`, the
    /// default, runs the branches one after another on this read.
    fn fork_read(&self) -> Option<Box<dyn GraphRead + '_>> {
        None
    }

    /// An operator is holding `rows` rows in memory right now. Report it at
    /// the point a buffer is largest; the profiler keeps the peak per
    /// operator. [`Self::check_intermediate_rows`] callers need not also call
    /// this: a backend that profiles records both.
    fn record_retained_rows(&self, _rows: usize) {}

    /// An operator materialized `vertices` whole vertex records outside
    /// [`Self::hydrate_vertices`], for example inside a bounded scan that
    /// hydrates as it walks.
    fn record_hydrated_vertices(&self, _vertices: usize) {}

    /// A statistics-chosen access finished or declined: what it estimated,
    /// what it read, and whether its fallback ran. For per-request
    /// observability; the default drops it.
    fn record_statistics_access(&self, _report: &StatisticsAccessReport) {}

    /// The most index entries one query may read, when the backend caps it.
    /// An access whose reads are bounded by its own limit rather than charged
    /// to that cap keeps under it. The default has no cap.
    fn max_query_index_candidates(&self) -> Option<usize> {
        None
    }
}

/// Starts a snapshot-consistent read session for one physical-plan execution.
// async_trait adds #[must_use] to boxed futures; Rust 1.99 already marks Future must_use.
#[allow(clippy::double_must_use, reason = "redundant attribute is generated by async_trait")]
#[async_trait]
pub trait GraphStorage: Send + Sync {
    async fn begin_read(&self, request: ReadRequest) -> StorageResult<Box<dyn GraphRead + '_>>;
}
